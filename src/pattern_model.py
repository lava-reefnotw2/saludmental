"""Score simulated GSHS profiles with the saved empirical CatBoost model."""

from math import isfinite
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from catboost import Pool


MODEL_ID = 'B1_catboost'
ARTIFACT_NAME = 'modelo_investigacion.joblib'
DOMAINS = {
    'age_years': range(13, 16),
    'sex_code': range(1, 3),
    'food_insecurity': range(1, 6),
    'physical_attack': range(1, 9),
    'physical_fight': range(1, 9),
    'close_friends': range(1, 5),
    'alcohol_30d': range(1, 8),
    'physical_activity': range(1, 9),
    'sedentary_time': range(1, 7),
}


class ModelUnavailable(ValueError):
    """The active run lacks the approved research model."""


def load_model(path: Path):
    # Only load the fixed artifact from the project's published local run.
    artifact = joblib.load(path)
    if (artifact.get('selected') != MODEL_ID
            or artifact.get('target') != 'y1_ideation'
            or artifact.get('research_only') is not True
            or tuple(artifact.get('features', ())) != tuple(DOMAINS)
            or not {'pipeline', 'calibrator'} <= artifact.keys()):
        raise ModelUnavailable('La ejecución activa no contiene el CatBoost compatible de P07.')
    return artifact


def _frame(profile):
    if profile.keys() != DOMAINS.keys() or any(
        type(profile[key]) is not int or profile[key] not in codes
        for key, codes in DOMAINS.items()
    ):
        raise ValueError('Completa las nueve respuestas con las opciones de la encuesta.')
    # Survey columns were fitted as floats so they could also represent missing answers.
    return pd.DataFrame([profile], columns=list(DOMAINS), dtype=float)


def _calibrated_score(artifact, frame):
    # Reproduce the same probability clipping and logit as the training recipe.
    raw = artifact['pipeline'].predict_proba(frame)[0, 1]
    clipped = np.clip(raw, 1e-6, 1 - 1e-6)
    logit = np.log(clipped / (1 - clipped))
    score = float(artifact['calibrator'].predict_proba([[logit]])[0, 1])
    if not isfinite(score) or not 0 <= score <= 1:
        raise ValueError('El modelo no devolvió una puntuación válida.')
    return score


def score_profile(artifact, profile):
    return _calibrated_score(artifact, _frame(profile))


def explain_profile(artifact, profile):
    frame = _frame(profile)
    pipeline = artifact['pipeline']
    encoded = pipeline[:-1].transform(frame)
    shap = pipeline.named_steps['model'].get_feature_importance(
        Pool(encoded), type='ShapValues', thread_count=1,
    )[0, :-1]

    # All columns generated by each answer are contiguous. The fitted encoder
    # uses neither dropped categories nor infrequent category grouping.
    categories = pipeline.named_steps['encode'].categories_
    widths = [len(levels) for levels in categories]
    if len(widths) != len(DOMAINS) or sum(widths) != len(shap):
        raise ModelUnavailable('La codificación del modelo no coincide con el formulario.')
    grouped = np.add.reduceat(shap, np.cumsum([0, *widths[:-1]]))
    effects = {key: float(effect) for key, effect in zip(DOMAINS, grouped)}
    return _calibrated_score(artifact, frame), effects
